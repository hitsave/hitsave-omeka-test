#!/usr/bin/env python3
"""Render omeka-dip-viewer/config/dip-s3.config.php from archiver Wasabi credentials + ingest.yaml."""
from __future__ import annotations

import sys
from pathlib import Path

try:
    import yaml
except ImportError as e:
    print(e, file=sys.stderr)
    sys.exit(1)

ROOT = Path(__file__).resolve().parents[2]
E2E = ROOT.parent
ARCHIVER = E2E / "hitsave-archiver"
ARCHIVER_CONFIG = E2E / "hitsave-archiver-config"
DEFAULT_CREDS = ARCHIVER_CONFIG / "secrets" / "wasabi-credentials.yaml"
DEFAULT_INGEST = ARCHIVER / "config" / "preservation" / "ingest.yaml"
if not DEFAULT_INGEST.is_file():
    DEFAULT_INGEST = ARCHIVER_CONFIG / "preservation" / "ingest.yaml"
OUT = E2E / "omeka-dip-viewer" / "config" / "dip-s3.config.php"


def load_yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def php_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> None:
    creds_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CREDS
    ingest_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_INGEST
    out_path = Path(sys.argv[3]) if len(sys.argv) > 3 else OUT

    if not creds_path.is_file():
        raise SystemExit(f"Missing Wasabi credentials: {creds_path}")
    creds_doc = load_yaml(creds_path)
    wasabi = creds_doc.get("wasabi") or creds_doc
    key = str(
        wasabi.get("access_key_id")
        or wasabi.get("access_key")
        or wasabi.get("key")
        or ""
    )
    secret = str(
        wasabi.get("secret_access_key")
        or wasabi.get("secret_key")
        or wasabi.get("secret")
        or ""
    )
    if not key or not secret:
        raise SystemExit(f"No access_key/secret_key in {creds_path}")

    ingest = load_yaml(ingest_path) if ingest_path.is_file() else {}
    ingest_wasabi = ingest.get("wasabi") or {}
    bucket = str(ingest_wasabi.get("bucket") or wasabi.get("bucket") or "hitsave-incoming")
    endpoint = str(
        ingest_wasabi.get("endpoint")
        or wasabi.get("endpoint")
        or wasabi.get("s3_endpoint")
        or "https://s3.us-east-2.wasabisys.com"
    )
    region = str(ingest_wasabi.get("region") or wasabi.get("region") or "us-east-2")

    body = f"""<?php
/**
 * Generated by hitsave-omeka-test/scripts/shell/render-dip-s3-config.py — do not commit.
 */
return [
    'endpoint' => {php_string(endpoint)},
    'region' => {php_string(region)},
    'bucket' => {php_string(bucket)},
    'credentials' => [
        'key' => {php_string(key)},
        'secret' => {php_string(secret)},
    ],
];
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(body, encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
