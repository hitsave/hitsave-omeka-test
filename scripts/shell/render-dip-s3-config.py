#!/usr/bin/env python3
"""Render omeka-dip-viewer/config/dip-s3.config.php from Omeka-only dip-s3.yaml (+ credentials file)."""
from __future__ import annotations

import sys
from pathlib import Path

try:
    import yaml
except ImportError as e:
    print(e, file=sys.stderr)
    sys.exit(1)

ROOT = Path(__file__).resolve().parents[2]
OMEKA_CONFIG = ROOT / "config" / "omeka-test"
DEFAULT_DIP_S3 = OMEKA_CONFIG / "dip-s3.yaml"
DEFAULT_OUT = ROOT.parent / "omeka-dip-viewer" / "config" / "dip-s3.config.php"


def load_yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def php_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def resolve_path(raw: str, *, base: Path) -> Path:
    path = Path(raw)
    if path.is_absolute():
        return path
    for root in (base, ROOT, OMEKA_CONFIG):
        candidate = root / path
        if candidate.is_file():
            return candidate
    return base / path


def load_credentials(dip_s3: dict, *, base: Path) -> tuple[str, str]:
    inline = dip_s3.get("credentials")
    if isinstance(inline, dict):
        key = str(
            inline.get("access_key_id")
            or inline.get("access_key")
            or inline.get("key")
            or ""
        ).strip()
        secret = str(
            inline.get("secret_access_key")
            or inline.get("secret_key")
            or inline.get("secret")
            or ""
        ).strip()
        if key and secret:
            return key, secret

    cred_file = dip_s3.get("credentials_file")
    if not cred_file or not str(cred_file).strip():
        raise SystemExit(
            "dip-s3.yaml must set credentials_file (see dip-s3-credentials.yaml.example) "
            "or a credentials: { access_key_id, secret_access_key } block"
        )
    cred_path = resolve_path(str(cred_file).strip(), base=base)
    if not cred_path.is_file():
        raise SystemExit(f"Missing Omeka Wasabi credentials file: {cred_path}")
    creds_doc = load_yaml(cred_path)
    wasabi = creds_doc.get("wasabi") or creds_doc
    key = str(
        wasabi.get("access_key_id")
        or wasabi.get("access_key")
        or wasabi.get("key")
        or ""
    ).strip()
    secret = str(
        wasabi.get("secret_access_key")
        or wasabi.get("secret_key")
        or wasabi.get("secret")
        or ""
    ).strip()
    if not key or not secret:
        raise SystemExit(f"No access_key_id/secret_access_key in {cred_path}")
    return key, secret


def main() -> None:
    dip_s3_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DIP_S3
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT

    if not dip_s3_path.is_file():
        raise SystemExit(
            f"Missing {dip_s3_path}\n"
            f"Copy {OMEKA_CONFIG / 'dip-s3.yaml.example'} to dip-s3.yaml and set Omeka Wasabi settings."
        )

    dip_s3 = load_yaml(dip_s3_path)
    bucket = str(dip_s3.get("bucket") or "").strip()
    endpoint = str(dip_s3.get("endpoint") or "").strip()
    region = str(dip_s3.get("region") or "").strip()
    if not endpoint or not region:
        raise SystemExit("dip-s3.yaml must set endpoint and region (bucket is optional)")

    key, secret = load_credentials(dip_s3, base=dip_s3_path.parent)

    body = f"""<?php
/**
 * Generated by hitsave-omeka-test/scripts/shell/render-dip-s3-config.py — do not commit.
 * Source: {dip_s3_path.name} (Omeka-only; not archiver ingest credentials).
 */
return [
    'endpoint' => {php_string(endpoint)},
    'region' => {php_string(region)},
    'bucket' => {php_string(bucket)},
    'credentials' => [
        'key' => {php_string(key)},
        'secret' => {php_string(secret)},
    ],
];
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(body, encoding="utf-8")
    print(f"Wrote {out_path} from {dip_s3_path}")


if __name__ == "__main__":
    main()
